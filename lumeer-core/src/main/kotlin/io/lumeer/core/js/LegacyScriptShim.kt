package io.lumeer.core.js

/**
 * Automation code generated by the blocks before calls moment, numbro and he directly. These functions keep it working
 * without the libraries: moment(date) records the calls and the lumeer bridge evaluates them (moment 2.31 semantics),
 * the other functions call the bridge.
 */
object LegacyScriptShim {

    /** Not a const: a const would be copied into the classes that use it and could go stale in incremental builds. */
    @JvmField
    val SCRIPT = """
var lumeer_shim = Polyglot.import('lumeer');
function LumeerMoment(date, operations) { this.d = date; this.ops = operations || []; }
LumeerMoment.prototype.op = function (name, args) { this.ops.push([name].concat(Array.prototype.slice.call(args))); return this; };
LumeerMoment.prototype.value = function () { return lumeer_shim.dateChain(this.d, this.ops); };
LumeerMoment.prototype.get = function (name) { return lumeer_shim.dateChain(this.d, this.ops.concat([[name]])); };
LumeerMoment.prototype.add = function () { return this.op('add', arguments); };
LumeerMoment.prototype.subtract = function () { return this.op('subtract', arguments); };
LumeerMoment.prototype.startOf = function () { return this.op('startOf', arguments); };
LumeerMoment.prototype.endOf = function () { return this.op('endOf', arguments); };
LumeerMoment.prototype.businessAdd = function (n) { return new LumeerMoment(this.d, this.ops.concat([['businessAdd', n]])); };
['date', 'second', 'minute', 'hour', 'week', 'month', 'quarter', 'year'].forEach(function (name) {
  LumeerMoment.prototype[name] = function (value) { return value == null ? this.get(name) : this.op(name, arguments); };
});
LumeerMoment.prototype.daysInMonth = function () { return this.get('daysInMonth'); };
LumeerMoment.prototype.toDate = function () { return new Date(this.value()); };
LumeerMoment.prototype.valueOf = function () { return this.value(); };
function moment(date) { return new LumeerMoment(arguments.length ? date : undefined); }
function formatMomentJsDate(time, format, locale) { return lumeer_shim.formatDate(time, format, locale); }
function parseMomentJsDate(date, format, locale) { return lumeer_shim.parseDate(date, format, locale); }
function lumeer_numbro(locale, decimals, num) { return lumeer_shim.formatCurrency(locale, decimals, num); }
var he = { escape: function (value) { return lumeer_shim.escapeHtml(value); }, unescape: function (value) { return lumeer_shim.unescapeHtml(value); } };
"""
}
