/**
 * Replays vectors generated by parity/vectors.mjs with the original JS library: the committed
 * src/jvmTest/resources/parity-vectors.json.gz, or a freshly generated file given by -Dparity.vectors.
 */
@Suppress("UNCHECKED_CAST")
class ParityVectorsTest {

    private class MapDocument(override val id: String, override val collectionId: String, private val data: Map<String, Any?>, override val parentId: String?) : DocumentModel {
        override fun value(attributeId: String): Any? = data[attributeId]
    }

    private fun Any?.asMap(): Map<String, Any?> = this as? Map<String, Any?> ?: emptyMap()
    private fun Any?.asList(): List<Any?> = this as? List<Any?> ?: emptyList()

    private fun user(value: Any?): User? = value?.asMap()?.let { User(it["id"] as String?, it["name"] as String?, it["email"] as String?) }

    private fun constraintData(map: Map<String, Any?>, now: Long): ConstraintData = ConstraintData(
        users = map["users"].asList().mapNotNull { user(it) },
        teams = map["teams"].asList().map { val t = it.asMap(); Team(t["id"] as String?, t["name"] as String?, t["users"].asList().map { u -> u as String }) },
        currentUser = user(map["currentUser"]),
        durationUnitsMap = map["durationUnitsMap"]?.asMap()?.mapValues { it.value as String },
        currencyData = map["currencyData"]?.asMap()?.let { CurrencyData(it["abbreviations"].asList().map { a -> a as String }, it["ordinals"].asList().map { o -> o as String }) },
        selectionLists = map["selectionLists"].asList().map {
            val l = it.asMap()
            SelectionList(l["id"] as String?, l["displayValues"] == true, l["options"].asList().map { o -> SelectOption(o.asMap()["value"], o.asMap()["displayValue"] as String?) })
        },
        timezone = map["timezone"] as String?,
        locale = map["locale"] as String?,
        nowMillis = now,
    )

    private fun conditionValues(list: Any?): List<ConditionValue> = list.asList().map { ConditionValue(it.asMap()["type"] as String?, it.asMap()["value"]) }

    private fun equation(value: Any?): AttributeFilterEquation? = value?.asMap()?.let { e ->
        val filter = e["filter"]?.asMap()
        AttributeFilterEquation(
            e["equations"].asList().mapNotNull { equation(it) },
            filter?.let { AttributeFilter(it["attributeId"] as String, ConditionType.fromValue(it["condition"] as String?), conditionValues(it["conditionValues"])) },
            EquationOperator.fromValue(e["operator"] as String?),
        )
    }

    private fun lock(value: Any?): AttributeLock? = value?.asMap()?.let { l ->
        AttributeLock(l["locked"] == true, l["exceptionGroups"].asList().map { g ->
            val group = g.asMap()
            AttributeLockExceptionGroup(group["type"] as String?, group["typeValue"].asList().map { it as String }, equation(group["equation"]))
        })
    }

    fun run(case: Map<String, Any?>): List<String> {
        val input = case["input"].asMap()
        val now = (case["now"] as Number).toLong()
        val documents = input["documents"].asList().map {
            val d = it.asMap()
            MapDocument(d["id"] as String, d["collectionId"] as String, d["data"].asMap(), d["metaData"]?.asMap()?.get("parentId") as String?)
        }
        val collections = input["collections"].asList().map {
            val c = it.asMap()
            Collection(c["id"] as String, c["attributes"].asList().map { a ->
                val attribute = a.asMap()
                val constraint = attribute["constraint"]?.asMap()
                Attribute(attribute["id"] as String, constraint?.let { createConstraint(it["type"] as String?, it["config"]?.asMap()) }, lock(attribute["lock"]))
            })
        }
        val query = input["query"].asMap()
        val stems = query["stems"].asList().map {
            val s = it.asMap()
            QueryStem(
                collectionId = s["collectionId"] as String,
                filters = s["filters"].asList().map { f ->
                    val filter = f.asMap()
                    CollectionAttributeFilter(filter["collectionId"] as String, filter["attributeId"] as String, ConditionType.fromValue(filter["condition"] as String?), conditionValues(filter["conditionValues"]))
                },
            )
        }
        val result = filterDocumentsAndLinksByQuery(
            documents, collections, emptyList(), emptyList<LinkInstanceModel>(),
            Query(stems, query["fulltexts"].asList().map { it as String }),
            constraintData(input["constraintData"].asMap(), now),
        )
        return result.documents.map { it.id }
    }

    @Test
    fun replayVectors() {
        val text = System.getProperty("parity.vectors")?.let { File(it).readText() }
            ?: GZIPInputStream(javaClass.getResourceAsStream("/parity-vectors.json.gz")!!).readBytes().decodeToString()
        val root = Json(text).parse().asMap()
        val originalZone = TimeZone.getDefault()
        (root["systemTimezone"] as String?)?.let { TimeZone.setDefault(TimeZone.getTimeZone(it)) }
        try {
            val failures = mutableMapOf<String, MutableList<String>>()
            var total = 0
            for (case in root["cases"].asList().map { it.asMap() }) {
                val expected = case["expected"] as? List<*> ?: continue
                total++
                val actual = try {
                    run(case)
                } catch (e: Exception) {
                    listOf("EXCEPTION " + e)
                }
                if (actual != expected) {
                    val input = case["input"].asMap()
                    val description = "case ${case["index"]}: expected=$expected actual=$actual\n" +
                        "  constraint=${input["collections"].asList().first().asMap()["attributes"]}\n" +
                        "  query=${input["query"]}\n  timezone=${input["constraintData"].asMap()["timezone"]} now=${case["now"]} language=${input["language"]}\n" +
                        "  values=${input["documents"].asList().map { it.asMap()["data"].asMap()["a1"] }}"
                    failures.getOrPut(case["type"] as String) { mutableListOf() }.add(description)
                }
            }
            val failed = failures.values.sumOf { it.size }
            println("Parity vectors: $total cases, $failed failures " + failures.mapValues { it.value.size })
            if (failed > 0) {
                fail("Parity failures by type: " + failures.mapValues { it.value.size } + "\n" + failures.values.flatMap { it.take(3) }.joinToString("\n"))
            }
        } finally {
            TimeZone.setDefault(originalZone)
        }
    }
}
